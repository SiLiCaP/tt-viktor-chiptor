module keccak_core #(parameter ROUNDS_PER_CLK = 1) (input wire clk, input wire rst_n, input wire start, input wire absorb,
  input wire [4:0] lane_sel, input wire [63:0] lane_in, output wire [63:0] lane_out, output reg busy);
  reg [63:0] A [0:24];  reg [4:0] rnd;
  function [63:0] rotl(input [63:0] v, input integer n); rotl = (n==0) ? v : ((v << n) | (v >> (64-n))); endfunction
  function [63:0] rc(input [4:0] r); case (r)
    5'd0: rc = 64'h0000000000000001;
    5'd1: rc = 64'h0000000000008082;
    5'd2: rc = 64'h800000000000808a;
    5'd3: rc = 64'h8000000080008000;
    5'd4: rc = 64'h000000000000808b;
    5'd5: rc = 64'h0000000080000001;
    5'd6: rc = 64'h8000000080008081;
    5'd7: rc = 64'h8000000000008009;
    5'd8: rc = 64'h000000000000008a;
    5'd9: rc = 64'h0000000000000088;
    5'd10: rc = 64'h0000000080008009;
    5'd11: rc = 64'h000000008000000a;
    5'd12: rc = 64'h000000008000808b;
    5'd13: rc = 64'h800000000000008b;
    5'd14: rc = 64'h8000000000008089;
    5'd15: rc = 64'h8000000000008003;
    5'd16: rc = 64'h8000000000008002;
    5'd17: rc = 64'h8000000000000080;
    5'd18: rc = 64'h000000000000800a;
    5'd19: rc = 64'h800000008000000a;
    5'd20: rc = 64'h8000000080008081;
    5'd21: rc = 64'h8000000000008080;
    5'd22: rc = 64'h0000000080000001;
    5'd23: rc = 64'h8000000080008008;
    default: rc = 64'h0; endcase endfunction
  wire [63:0] C0 [0:4]; wire [63:0] D0 [0:4]; wire [63:0] B0 [0:24]; wire [63:0] N0 [0:24];
  assign C0[0] = A[0+5*0] ^ A[0+5*1] ^ A[0+5*2] ^ A[0+5*3] ^ A[0+5*4];
  assign C0[1] = A[1+5*0] ^ A[1+5*1] ^ A[1+5*2] ^ A[1+5*3] ^ A[1+5*4];
  assign C0[2] = A[2+5*0] ^ A[2+5*1] ^ A[2+5*2] ^ A[2+5*3] ^ A[2+5*4];
  assign C0[3] = A[3+5*0] ^ A[3+5*1] ^ A[3+5*2] ^ A[3+5*3] ^ A[3+5*4];
  assign C0[4] = A[4+5*0] ^ A[4+5*1] ^ A[4+5*2] ^ A[4+5*3] ^ A[4+5*4];
  assign D0[0] = C0[4] ^ rotl(C0[1], 1);
  assign D0[1] = C0[0] ^ rotl(C0[2], 1);
  assign D0[2] = C0[1] ^ rotl(C0[3], 1);
  assign D0[3] = C0[2] ^ rotl(C0[4], 1);
  assign D0[4] = C0[3] ^ rotl(C0[0], 1);
  assign B0[0+5*0] = rotl(A[0+5*0] ^ D0[0], 0);
  assign B0[1+5*3] = rotl(A[0+5*1] ^ D0[0], 36);
  assign B0[2+5*1] = rotl(A[0+5*2] ^ D0[0], 3);
  assign B0[3+5*4] = rotl(A[0+5*3] ^ D0[0], 41);
  assign B0[4+5*2] = rotl(A[0+5*4] ^ D0[0], 18);
  assign B0[0+5*2] = rotl(A[1+5*0] ^ D0[1], 1);
  assign B0[1+5*0] = rotl(A[1+5*1] ^ D0[1], 44);
  assign B0[2+5*3] = rotl(A[1+5*2] ^ D0[1], 10);
  assign B0[3+5*1] = rotl(A[1+5*3] ^ D0[1], 45);
  assign B0[4+5*4] = rotl(A[1+5*4] ^ D0[1], 2);
  assign B0[0+5*4] = rotl(A[2+5*0] ^ D0[2], 62);
  assign B0[1+5*2] = rotl(A[2+5*1] ^ D0[2], 6);
  assign B0[2+5*0] = rotl(A[2+5*2] ^ D0[2], 43);
  assign B0[3+5*3] = rotl(A[2+5*3] ^ D0[2], 15);
  assign B0[4+5*1] = rotl(A[2+5*4] ^ D0[2], 61);
  assign B0[0+5*1] = rotl(A[3+5*0] ^ D0[3], 28);
  assign B0[1+5*4] = rotl(A[3+5*1] ^ D0[3], 55);
  assign B0[2+5*2] = rotl(A[3+5*2] ^ D0[3], 25);
  assign B0[3+5*0] = rotl(A[3+5*3] ^ D0[3], 21);
  assign B0[4+5*3] = rotl(A[3+5*4] ^ D0[3], 56);
  assign B0[0+5*3] = rotl(A[4+5*0] ^ D0[4], 27);
  assign B0[1+5*1] = rotl(A[4+5*1] ^ D0[4], 20);
  assign B0[2+5*4] = rotl(A[4+5*2] ^ D0[4], 39);
  assign B0[3+5*2] = rotl(A[4+5*3] ^ D0[4], 8);
  assign B0[4+5*0] = rotl(A[4+5*4] ^ D0[4], 14);
  assign N0[0+5*0] = B0[0+5*0] ^ (~B0[1+5*0] & B0[2+5*0]) ^ rc(rnd);
  assign N0[0+5*1] = B0[0+5*1] ^ (~B0[1+5*1] & B0[2+5*1]);
  assign N0[0+5*2] = B0[0+5*2] ^ (~B0[1+5*2] & B0[2+5*2]);
  assign N0[0+5*3] = B0[0+5*3] ^ (~B0[1+5*3] & B0[2+5*3]);
  assign N0[0+5*4] = B0[0+5*4] ^ (~B0[1+5*4] & B0[2+5*4]);
  assign N0[1+5*0] = B0[1+5*0] ^ (~B0[2+5*0] & B0[3+5*0]);
  assign N0[1+5*1] = B0[1+5*1] ^ (~B0[2+5*1] & B0[3+5*1]);
  assign N0[1+5*2] = B0[1+5*2] ^ (~B0[2+5*2] & B0[3+5*2]);
  assign N0[1+5*3] = B0[1+5*3] ^ (~B0[2+5*3] & B0[3+5*3]);
  assign N0[1+5*4] = B0[1+5*4] ^ (~B0[2+5*4] & B0[3+5*4]);
  assign N0[2+5*0] = B0[2+5*0] ^ (~B0[3+5*0] & B0[4+5*0]);
  assign N0[2+5*1] = B0[2+5*1] ^ (~B0[3+5*1] & B0[4+5*1]);
  assign N0[2+5*2] = B0[2+5*2] ^ (~B0[3+5*2] & B0[4+5*2]);
  assign N0[2+5*3] = B0[2+5*3] ^ (~B0[3+5*3] & B0[4+5*3]);
  assign N0[2+5*4] = B0[2+5*4] ^ (~B0[3+5*4] & B0[4+5*4]);
  assign N0[3+5*0] = B0[3+5*0] ^ (~B0[4+5*0] & B0[0+5*0]);
  assign N0[3+5*1] = B0[3+5*1] ^ (~B0[4+5*1] & B0[0+5*1]);
  assign N0[3+5*2] = B0[3+5*2] ^ (~B0[4+5*2] & B0[0+5*2]);
  assign N0[3+5*3] = B0[3+5*3] ^ (~B0[4+5*3] & B0[0+5*3]);
  assign N0[3+5*4] = B0[3+5*4] ^ (~B0[4+5*4] & B0[0+5*4]);
  assign N0[4+5*0] = B0[4+5*0] ^ (~B0[0+5*0] & B0[1+5*0]);
  assign N0[4+5*1] = B0[4+5*1] ^ (~B0[0+5*1] & B0[1+5*1]);
  assign N0[4+5*2] = B0[4+5*2] ^ (~B0[0+5*2] & B0[1+5*2]);
  assign N0[4+5*3] = B0[4+5*3] ^ (~B0[0+5*3] & B0[1+5*3]);
  assign N0[4+5*4] = B0[4+5*4] ^ (~B0[0+5*4] & B0[1+5*4]);
  generate if (ROUNDS_PER_CLK == 2) begin : g2
  wire [63:0] C1 [0:4]; wire [63:0] D1 [0:4]; wire [63:0] B1 [0:24]; wire [63:0] N1 [0:24];
  assign C1[0] = N0[0+5*0] ^ N0[0+5*1] ^ N0[0+5*2] ^ N0[0+5*3] ^ N0[0+5*4];
  assign C1[1] = N0[1+5*0] ^ N0[1+5*1] ^ N0[1+5*2] ^ N0[1+5*3] ^ N0[1+5*4];
  assign C1[2] = N0[2+5*0] ^ N0[2+5*1] ^ N0[2+5*2] ^ N0[2+5*3] ^ N0[2+5*4];
  assign C1[3] = N0[3+5*0] ^ N0[3+5*1] ^ N0[3+5*2] ^ N0[3+5*3] ^ N0[3+5*4];
  assign C1[4] = N0[4+5*0] ^ N0[4+5*1] ^ N0[4+5*2] ^ N0[4+5*3] ^ N0[4+5*4];
  assign D1[0] = C1[4] ^ rotl(C1[1], 1);
  assign D1[1] = C1[0] ^ rotl(C1[2], 1);
  assign D1[2] = C1[1] ^ rotl(C1[3], 1);
  assign D1[3] = C1[2] ^ rotl(C1[4], 1);
  assign D1[4] = C1[3] ^ rotl(C1[0], 1);
  assign B1[0+5*0] = rotl(N0[0+5*0] ^ D1[0], 0);
  assign B1[1+5*3] = rotl(N0[0+5*1] ^ D1[0], 36);
  assign B1[2+5*1] = rotl(N0[0+5*2] ^ D1[0], 3);
  assign B1[3+5*4] = rotl(N0[0+5*3] ^ D1[0], 41);
  assign B1[4+5*2] = rotl(N0[0+5*4] ^ D1[0], 18);
  assign B1[0+5*2] = rotl(N0[1+5*0] ^ D1[1], 1);
  assign B1[1+5*0] = rotl(N0[1+5*1] ^ D1[1], 44);
  assign B1[2+5*3] = rotl(N0[1+5*2] ^ D1[1], 10);
  assign B1[3+5*1] = rotl(N0[1+5*3] ^ D1[1], 45);
  assign B1[4+5*4] = rotl(N0[1+5*4] ^ D1[1], 2);
  assign B1[0+5*4] = rotl(N0[2+5*0] ^ D1[2], 62);
  assign B1[1+5*2] = rotl(N0[2+5*1] ^ D1[2], 6);
  assign B1[2+5*0] = rotl(N0[2+5*2] ^ D1[2], 43);
  assign B1[3+5*3] = rotl(N0[2+5*3] ^ D1[2], 15);
  assign B1[4+5*1] = rotl(N0[2+5*4] ^ D1[2], 61);
  assign B1[0+5*1] = rotl(N0[3+5*0] ^ D1[3], 28);
  assign B1[1+5*4] = rotl(N0[3+5*1] ^ D1[3], 55);
  assign B1[2+5*2] = rotl(N0[3+5*2] ^ D1[3], 25);
  assign B1[3+5*0] = rotl(N0[3+5*3] ^ D1[3], 21);
  assign B1[4+5*3] = rotl(N0[3+5*4] ^ D1[3], 56);
  assign B1[0+5*3] = rotl(N0[4+5*0] ^ D1[4], 27);
  assign B1[1+5*1] = rotl(N0[4+5*1] ^ D1[4], 20);
  assign B1[2+5*4] = rotl(N0[4+5*2] ^ D1[4], 39);
  assign B1[3+5*2] = rotl(N0[4+5*3] ^ D1[4], 8);
  assign B1[4+5*0] = rotl(N0[4+5*4] ^ D1[4], 14);
  assign N1[0+5*0] = B1[0+5*0] ^ (~B1[1+5*0] & B1[2+5*0]) ^ rc(rnd + 5'd1);
  assign N1[0+5*1] = B1[0+5*1] ^ (~B1[1+5*1] & B1[2+5*1]);
  assign N1[0+5*2] = B1[0+5*2] ^ (~B1[1+5*2] & B1[2+5*2]);
  assign N1[0+5*3] = B1[0+5*3] ^ (~B1[1+5*3] & B1[2+5*3]);
  assign N1[0+5*4] = B1[0+5*4] ^ (~B1[1+5*4] & B1[2+5*4]);
  assign N1[1+5*0] = B1[1+5*0] ^ (~B1[2+5*0] & B1[3+5*0]);
  assign N1[1+5*1] = B1[1+5*1] ^ (~B1[2+5*1] & B1[3+5*1]);
  assign N1[1+5*2] = B1[1+5*2] ^ (~B1[2+5*2] & B1[3+5*2]);
  assign N1[1+5*3] = B1[1+5*3] ^ (~B1[2+5*3] & B1[3+5*3]);
  assign N1[1+5*4] = B1[1+5*4] ^ (~B1[2+5*4] & B1[3+5*4]);
  assign N1[2+5*0] = B1[2+5*0] ^ (~B1[3+5*0] & B1[4+5*0]);
  assign N1[2+5*1] = B1[2+5*1] ^ (~B1[3+5*1] & B1[4+5*1]);
  assign N1[2+5*2] = B1[2+5*2] ^ (~B1[3+5*2] & B1[4+5*2]);
  assign N1[2+5*3] = B1[2+5*3] ^ (~B1[3+5*3] & B1[4+5*3]);
  assign N1[2+5*4] = B1[2+5*4] ^ (~B1[3+5*4] & B1[4+5*4]);
  assign N1[3+5*0] = B1[3+5*0] ^ (~B1[4+5*0] & B1[0+5*0]);
  assign N1[3+5*1] = B1[3+5*1] ^ (~B1[4+5*1] & B1[0+5*1]);
  assign N1[3+5*2] = B1[3+5*2] ^ (~B1[4+5*2] & B1[0+5*2]);
  assign N1[3+5*3] = B1[3+5*3] ^ (~B1[4+5*3] & B1[0+5*3]);
  assign N1[3+5*4] = B1[3+5*4] ^ (~B1[4+5*4] & B1[0+5*4]);
  assign N1[4+5*0] = B1[4+5*0] ^ (~B1[0+5*0] & B1[1+5*0]);
  assign N1[4+5*1] = B1[4+5*1] ^ (~B1[0+5*1] & B1[1+5*1]);
  assign N1[4+5*2] = B1[4+5*2] ^ (~B1[0+5*2] & B1[1+5*2]);
  assign N1[4+5*3] = B1[4+5*3] ^ (~B1[0+5*3] & B1[1+5*3]);
  assign N1[4+5*4] = B1[4+5*4] ^ (~B1[0+5*4] & B1[1+5*4]);
  end endgenerate
  integer i;
  always @(posedge clk) begin
    if (!rst_n) begin for (i = 0; i < 25; i = i + 1) A[i] <= 64'd0; rnd <= 0; busy <= 0; end
    else if (busy) begin
      for (i = 0; i < 25; i = i + 1) A[i] <= (ROUNDS_PER_CLK == 2) ? g2.N1[i] : N0[i];
      rnd <= rnd + ROUNDS_PER_CLK; if (rnd + ROUNDS_PER_CLK == 24) busy <= 0;
    end else if (start) begin rnd <= 0; busy <= 1; end
    else if (absorb) A[lane_sel] <= A[lane_sel] ^ lane_in;
  end
  assign lane_out = A[lane_sel];
endmodule
